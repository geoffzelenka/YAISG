@dataclass(frozen=True)
class Caps:
    """Resolved limits which constrain character activity."""

    offline_hours: float
    inventory_slots: int
    order_slots: int
    key_listings: int
    belt_slots: int
    estate_upgrade_slots: int


@dataclass(frozen=True)
class CharacterState:
    """All character data needed by the pure action engine."""

    skills_xp: Mapping[str, int]
    skill_levels: Mapping[str, int]
    inventory: Mapping[str, int]
    gold: int
    estate_form_id: str
    realm_node_id: str
    current_realm_id: str = ""
    estate_realm_id: str = ""
    realm_stage: DecayStage = DecayStage.FED
    estate_stage: DecayStage = DecayStage.FED
    realm_stack_tags: tuple[str, ...] = ()
    gear_modifiers: tuple[Modifier, ...] = ()
    consumable_modifiers: tuple[Modifier, ...] = ()
    installed_upgrades: tuple[str, ...] = ()
    cap_bonuses: Mapping[CapType, float] = field(default_factory=dict)


@dataclass(frozen=True)
class ActiveAction:
    """Timestamps for a character's currently repeating action."""

    action_id: str
    started_at: datetime
    last_resolved_at: datetime
    meta: Mapping[str, Any] = field(default_factory=dict)


class StopReason(StrEnum):
    """Reasons resolution automatically ends an action."""

    REQUIREMENT_LOST = "REQUIREMENT_LOST"
    INPUTS_EXHAUSTED = "inputs_exhausted"
    OFFLINE_CAP = "offline_cap"
    INVENTORY_FULL = "inventory_full"


@dataclass(frozen=True)
class ResolveResult:
    """Summary of changes produced by one lazy resolution call."""

    cycles_completed: int
    xp_gained: Mapping[str, int]
    items_consumed: Mapping[str, int]
    items_gained: Mapping[str, int]
    overflowed_items: Mapping[str, int]
    level_ups: Mapping[str, tuple[int, ...]]
    stop_reason: StopReason | None
    state: CharacterState | None = None
    active: ActiveAction | None = None
    elapsed_ms: int = 0
    details: Mapping[str, Any] = field(default_factory=dict)


class ErrorCode(StrEnum):
    """Stable error codes returned by action-start validation."""

    INSUFFICIENT_LEVEL = "INSUFFICIENT_LEVEL"
    NOT_OFFERED_HERE = "NOT_OFFERED_HERE"
    MISSING_FACILITY = "MISSING_FACILITY"
    MISSING_REALM_TAG = "MISSING_REALM_TAG"
    MISSING_SKILL_LEVEL = "MISSING_SKILL_LEVEL"
    MISSING_TOOL = "MISSING_TOOL"
    MISSING_INPUTS = "MISSING_INPUTS"


@dataclass(frozen=True)
class Ok:
    """Successful result from action-start validation."""


OK = Ok()


class RandomSource(Protocol):
    """Random operations used by drop resolution."""

    def random(self) -> float:
        """Return a value in the half-open interval [0, 1)."""

    def randint(self, a: int, b: int) -> int:
        """Return an integer in the inclusive interval [a, b]."""


@dataclass(frozen=True)
class CycleRewards:
    """Rewards generated by one action cycle."""

    xp: int
    drops: tuple[tuple[str, int], ...]


@dataclass(frozen=True)
class ResolveContext:
    """Content, initial bonuses, caps and action state for a clipped budget."""

    content: ContentIndex
    active: ActiveAction
    caps: Caps
    modifier_groups: tuple[tuple[Modifier, ...], ...]


class ActionResolver(Protocol):
    """Pure action-specific simulation over an already clipped time budget."""

    def resolve(
        self,
        state: CharacterState,
        action: Action,
        ctx: ResolveContext,
        budget_ms: int,
        rng: RandomSource,
    ) -> ResolveResult:
        """Return changed state, rewards, consumed time and action progress."""


def home_realm(character: CharacterState) -> str:
    """Return the realm where the character owns their estate."""
    return character.estate_realm_id


def is_resident(character: CharacterState, realm: str) -> bool:
    """Return whether the character's estate is located in this realm."""
    return home_realm(character) == realm


def is_present(character: CharacterState, realm: str) -> bool:
    """Return whether the character is currently in this realm."""
    return character.current_realm_id == realm


def realm_active_tags(
    state: CharacterState, content: ContentIndex
) -> tuple[tuple[Tag, float], ...]:
    """Resolve inherent and supplied stack tags for the current realm."""
    node = content.development_node(state.realm_node_id)
    return _activate(
        node.inherent_tags + state.realm_stack_tags,
        state.realm_stage,
        content,
    )


def _activate(
    ids: Sequence[str], stage: DecayStage, content: ContentIndex
) -> tuple[tuple[Tag, float], ...]:
    definitions = {tag.id: tag for tag in content.tags}
    return active_tags(
        TagHolder(
            tuple(definitions[i] for i in dict.fromkeys(ids)),
            content.economy.decay.faltering_factor,
        ),
        stage,
    )


def _realm_tags(state: CharacterState, content: ContentIndex) -> set[str]:
    return {tag.id for tag, _ in realm_active_tags(state, content)}


def _estate_sources(
    state: CharacterState, content: ContentIndex
) -> tuple[EstateForm | EstateUpgrade, ...]:
    if not is_present(state, home_realm(state)):
        return ()
    realm = _realm_tags(state, content)
    form = content.estate_form(state.estate_form_id)
    sources: list[EstateForm | EstateUpgrade] = []
    if tags_present(form.requires_realm_tags, realm):
        sources.append(form)
    for identifier in state.installed_upgrades:
        upgrade = content.upgrade(identifier)
        if tags_present(upgrade.requires_realm_tags, realm):
            sources.append(upgrade)
    return tuple(sources)


def estate_active_tags(
    state: CharacterState, content: ContentIndex
) -> tuple[tuple[Tag, float], ...]:
    """Resolve only present, non-inert estate emissions."""
    return _activate(
        tuple(i for source in _estate_sources(state, content) for i in source.tags),
        state.estate_stage,
        content,
    )


def tag_modifiers(tags: tuple[tuple[Tag, float], ...]) -> tuple[Modifier, ...]:
    """Scale tag modifiers without changing authored content."""
    return tuple(
        m.model_copy(update={"value": m.value * factor})
        for tag, factor in tags
        for m in tag.modifiers
    )


def tier_distance(action: Action, state: CharacterState, content: ContentIndex) -> int:
    """Return the action's distance below the character's skill tier."""
    tier = tier_for_level(
        state.skill_levels.get(action.skill_id, 1), content.progression.tier_thresholds
    )
    return max(0, tier - action.tier)


def proficiency_pct(
    action: Action, state: CharacterState, content: ContentIndex
) -> float:
    """Look up the speed-only proficiency percentage."""
    category = content.skill(action.skill_id).category
    return content.progression.proficiency[category][
        tier_distance(action, state, content)
    ]


def taper_factor(action: Action, state: CharacterState, content: ContentIndex) -> float:
    """Look up the XP taper (combat uses this for offense only)."""
    category = content.skill(action.skill_id).category
    return content.progression.taper[category][tier_distance(action, state, content)]


def modifier_groups(
    state: CharacterState, content: ContentIndex
) -> tuple[tuple[Modifier, ...], ...]:
    """Provide G, E, R and C, excluding absent estates and inert upgrades."""
    node = content.development_node(state.realm_node_id)
    estate = tuple(
        m for source in _estate_sources(state, content) for m in source.modifiers
    )
    return (
        state.gear_modifiers,
        estate + tag_modifiers(estate_active_tags(state, content)),
        node.modifiers + tag_modifiers(realm_active_tags(state, content)),
        state.consumable_modifiers,
    )


def modifier_applies(
    modifier: Modifier, skill_id: str, category: SkillCategory
) -> bool:
    """Return whether a modifier's skill/category scope includes this skill."""
    return (modifier.skill_id is None or modifier.skill_id == skill_id) and (
        modifier.category is None or modifier.category == category
    )


def bonus_total(
    modifier_type: ModifierType,
    action: Action,
    state: CharacterState,
    content: ContentIndex,
) -> float:
    """Add matching percentages within groups, then multiply group factors."""
    category = content.skill(action.skill_id).category
    factors = []
    for group in modifier_groups(state, content):
        percent = sum(
            m.value
            for m in group
            if m.type == modifier_type
            and modifier_applies(m, action.skill_id, category)
        )
        factors.append(max(content.progression.min_factor, 1 + percent / 100))
    percent = (
        proficiency_pct(action, state, content)
        if modifier_type == ModifierType.CYCLE_SPEED_PCT
        else 0
    )
    factors.append(max(content.progression.min_factor, 1 + percent / 100))
    return math.prod(factors)


def effective_cycle_time(
    action: Action, state: CharacterState, content: ContentIndex
) -> int:
    """Floor base time divided by speed, respecting the content minimum."""
    total = bonus_total(ModifierType.CYCLE_SPEED_PCT, action, state, content)
    return max(
        content.progression.min_cycle_ms, math.floor(action.base_cycle_ms / total)
    )


def xp_factors(
    action: Action, state: CharacterState, content: ContentIndex
) -> tuple[float, float]:
    """Return uncapped and capped XP multipliers before taper."""
    total = bonus_total(ModifierType.XP_PCT, action, state, content)
    return total, min(total, 1 + content.progression.xp_bonus_cap_pct / 100)


def effective_xp(action: Action, state: CharacterState, content: ContentIndex) -> int:
    """Apply the XP cap, then taper, then floor once."""
    return math.floor(
        action.xp
        * xp_factors(action, state, content)[1]
        * taper_factor(action, state, content)
    )


def effective_drops(
    action: Action, state: CharacterState, content: ContentIndex
) -> tuple[Drop, ...]:
    """Multiply drop chances and clamp each to the probability interval."""
    total = bonus_total(ModifierType.EXTRA_DROP_CHANCE_PCT, action, state, content)
    return tuple(
        drop.model_copy(update={"chance": min(1.0, max(0.0, drop.chance * total))})
        for drop in action.outputs
    )


class StandardCycleRewards:
    """Standard skilling XP and random drop-table rewards."""

    def rewards_from_values(
        self, xp: int, drops: Sequence[Drop], rng: RandomSource
    ) -> CycleRewards:
        """Roll rewards from effective values cached for a resolution segment."""
        rolled_drops = tuple(
            (drop.item_id, rng.randint(drop.quantity_min, drop.quantity_max))
            for drop in drops
            if rng.random() < drop.chance
        )
        return CycleRewards(xp, rolled_drops)


STANDARD_REWARDS = StandardCycleRewards()


def resolve_caps(state: CharacterState, content: ContentIndex) -> Caps:
    """Resolve global, estate-form, development-node, and upgrade caps."""
    bonuses: defaultdict[CapType, float] = defaultdict(float, state.cap_bonuses)
    for source in _estate_sources(state, content):
        if isinstance(source, EstateForm):
            for cap, value in source.base_caps.items():
                bonuses[cap] += value
        else:
            for bonus in source.cap_bonuses:
                bonuses[bonus.cap] += bonus.value
    node = content.development_node(state.realm_node_id)
    for bonus in node.cap_bonuses:
        bonuses[bonus.cap] += bonus.value
    for tag, _ in realm_active_tags(state, content) + estate_active_tags(
        state, content
    ):
        for cap, value in tag.cap_bonuses.items():
            bonuses[cap] += value
    base = content.caps
    return Caps(
        offline_hours=base.offline_hours + bonuses[CapType.OFFLINE_HOURS],
        inventory_slots=int(base.inventory_slots + bonuses[CapType.INVENTORY_SLOTS]),
        order_slots=int(base.order_slots + bonuses[CapType.ORDER_SLOTS]),
        key_listings=int(base.key_listings + bonuses[CapType.KEY_LISTINGS]),
        belt_slots=int(base.belt_slots + bonuses[CapType.BELT_SLOTS]),
        estate_upgrade_slots=int(
            base.estate_upgrade_slots + bonuses[CapType.ESTATE_UPGRADE_SLOTS]
        ),
    )


def path_cost(realm_a: str, realm_b: str, content: ContentIndex) -> MapCost:
    """Return the cheapest map path, tied by gold and then elapsed time.

    Item quantities do not participate in ordering because different item bags
    are not inherently comparable. They are summed along the selected path.
    """
    if realm_a not in {realm.id for realm in content.realms} or realm_b not in {
        realm.id for realm in content.realms
    }:
        raise ValueError("path endpoint is not a known realm")
    if realm_a == realm_b:
        return MapCost(gold=0, items=(), time_ms=0)
    graph: defaultdict[str, list[tuple[str, MapCost]]] = defaultdict(list)
    for edge in content.map.edges:
        left, right = edge.realms
        graph[left].append((right, edge.cost))
        graph[right].append((left, edge.cost))
    sequence = itertools.count()
    queue: list[tuple[int, int, int, str, dict[str, int]]] = [
        (0, 0, next(sequence), realm_a, {})
    ]
    best: dict[str, tuple[int, int]] = {}
    while queue:
        gold, elapsed, _, realm, items = heapq.heappop(queue)
        if best.get(realm, (gold + 1, elapsed + 1)) <= (gold, elapsed):
            continue
        best[realm] = (gold, elapsed)
        if realm == realm_b:
            return MapCost(
                gold=gold,
                time_ms=elapsed,
                items=tuple(
                    ItemQuantity(item_id=item_id, qty=qty)
                    for item_id, qty in sorted(items.items())
                ),
            )
        for destination, edge_cost in graph[realm]:
            edge_items = dict(items)
            for entry in edge_cost.items:
                edge_items[entry.item_id] = edge_items.get(entry.item_id, 0) + entry.qty
            heapq.heappush(
                queue,
                (
                    gold + edge_cost.gold,
                    elapsed + edge_cost.time_ms,
                    next(sequence),
                    destination,
                    edge_items,
                ),
            )
    raise ValueError(f"no map path from {realm_a!r} to {realm_b!r}")


def relocation_cost(cost: MapCost, form: EstateForm, content: ContentIndex) -> MapCost:
    """Apply relocation multipliers, omitting item quantities truncated to zero."""
    relocation_class = content.relocation_classes[form.relocation_class]
    return MapCost(
        gold=int(cost.gold * relocation_class.cost_multiplier),
        time_ms=int(cost.time_ms * relocation_class.time_multiplier),
        items=tuple(
            ItemQuantity(
                item_id=entry.item_id,
                qty=int(entry.qty * relocation_class.cost_multiplier),
            )
            for entry in cost.items
            if int(entry.qty * relocation_class.cost_multiplier) > 0
        ),
    )


def input_payment(
    holding: Mapping[str, int], action: Action, content: ContentIndex
) -> dict[str, int] | None:
    """Plan all inputs in content order, accounting for overlapping selectors."""
    remaining = dict(holding)
    payment: defaultdict[str, int] = defaultdict(int)
    for entry in action.inputs:
        result = pay_selector(remaining, entry.selector, entry.quantity, content)
        if isinstance(result, Shortfall):
            return None
        for item_id, quantity in result.items():
            remaining[item_id] -= quantity
            payment[item_id] += quantity
    return dict(payment)


def unmet_requirements(
    action: Action, state: CharacterState, content: ContentIndex
) -> tuple[ErrorCode, ...]:
    """Report every failed gate in a stable order for both report and start."""
    blocked: list[ErrorCode] = []
    if state.skill_levels.get(action.skill_id, 1) < action.unlock_level:
        blocked.append(ErrorCode.INSUFFICIENT_LEVEL)
    category = content.skill(action.skill_id).category
    if (
        category in {"gathering", "combat", "exploration"}
        and action.id not in content.development_node(state.realm_node_id).actions
    ):
        blocked.append(ErrorCode.NOT_OFFERED_HERE)
    realm = realm_active_tags(state, content)
    facilities = {
        tag.id
        for tag, _ in realm + estate_active_tags(state, content)
        if tag.kind == "facility"
    }
    if (
        action.requires.facility is not None
        and action.requires.facility not in facilities
    ):
        blocked.append(ErrorCode.MISSING_FACILITY)
    if not tags_present(action.requires.realm_tags, {tag.id for tag, _ in realm}):
        blocked.append(ErrorCode.MISSING_REALM_TAG)
    if any(
        state.skill_levels.get(skill, 1) < level
        for skill, level in action.requires.skill_levels.items()
    ):
        blocked.append(ErrorCode.MISSING_SKILL_LEVEL)
    if action.requires.tool_class is not None:
        blocked.append(ErrorCode.MISSING_TOOL)
    if input_payment(state.inventory, action, content) is None:
        blocked.append(ErrorCode.MISSING_INPUTS)
    return tuple(blocked)


def can_start(
    action_id: str, state: CharacterState, content: ContentIndex
) -> Ok | ErrorCode:
    """Use the same requirements as the availability report."""
    blocked = unmet_requirements(content.action(action_id), state, content)
    return blocked[0] if blocked else OK


def _milliseconds(delta: timedelta) -> int:
    return delta.days * 86_400_000 + delta.seconds * 1_000 + delta.microseconds // 1_000


def _resolve_uniform(
    state: CharacterState,
    action: Action,
    ctx: ResolveContext,
    available_ms: int,
    rng: RandomSource,
) -> ResolveResult:
    """Resolve full uniform cycles, recomputing values at level changes."""
    content, active, caps = ctx.content, ctx.active, ctx.caps
    inventory = {item_id: qty for item_id, qty in state.inventory.items() if qty > 0}
    xp = dict(state.skills_xp)
    levels = dict(state.skill_levels)
    consumed: defaultdict[str, int] = defaultdict(int)
    gained: defaultdict[str, int] = defaultdict(int)
    overflowed: defaultdict[str, int] = defaultdict(int)
    level_ups: defaultdict[str, list[int]] = defaultdict(list)
    resolved_ms = 0
    cycles = 0
    stop_reason: StopReason | None = None
    effective_level: int | None = None
    cycle_ms = 0
    standard_xp = 0
    standard_drops: tuple[Drop, ...] = ()

    while True:
        current_state = replace(
            state, skills_xp=xp, skill_levels=levels, inventory=inventory
        )
        current_level = levels.get(action.skill_id, 1)
        if current_level != effective_level:
            cycle_ms = effective_cycle_time(action, current_state, content)
            standard_xp = effective_xp(action, current_state, content)
            standard_drops = effective_drops(action, current_state, content)
            effective_level = current_level
        if resolved_ms + cycle_ms > available_ms:
            break
        payment = input_payment(inventory, action, content)
        if payment is None:
            stop_reason = StopReason.INPUTS_EXHAUSTED
            break
        for item_id, quantity in payment.items():
            inventory[item_id] -= quantity
            consumed[item_id] += quantity
            if inventory[item_id] == 0:
                del inventory[item_id]

        rewards = STANDARD_REWARDS.rewards_from_values(standard_xp, standard_drops, rng)
        skill_xp = xp.get(action.skill_id, 0) + rewards.xp
        previous_level = levels.get(action.skill_id, 1)
        next_level = level_for_xp(skill_xp, content.xp_curve.levels)
        xp[action.skill_id] = skill_xp
        levels[action.skill_id] = next_level
        if next_level > previous_level:
            level_ups[action.skill_id].extend(range(previous_level + 1, next_level + 1))

        cycle_overflow = False
        for item_id, quantity in rewards.drops:
            current_quantity = inventory.get(item_id, 0)
            has_slot = item_id in inventory or len(inventory) < caps.inventory_slots
            available_stack = max(
                0, content.item(item_id).stack_limit - current_quantity
            )
            granted = min(quantity, available_stack) if has_slot else 0
            discarded = quantity - granted
            if granted:
                inventory[item_id] = current_quantity + granted
                gained[item_id] += granted
            if discarded:
                overflowed[item_id] += discarded
                cycle_overflow = True
        cycles += 1
        resolved_ms += cycle_ms
        # Capacity loss takes precedence when the same cycle also exhausts inputs:
        # it is the first irreversible constraint encountered while granting rewards.
        if cycle_overflow:
            stop_reason = StopReason.INVENTORY_FULL
            break
        if action.inputs and input_payment(inventory, action, content) is None:
            stop_reason = StopReason.INPUTS_EXHAUSTED
            break

    new_state = replace(state, skills_xp=xp, skill_levels=levels, inventory=inventory)
    xp_delta = xp.get(action.skill_id, 0) - state.skills_xp.get(action.skill_id, 0)
    new_active = (
        None
        if stop_reason is not None
        else replace(
            active,
            last_resolved_at=active.last_resolved_at
            + timedelta(milliseconds=resolved_ms),
        )
    )
    return ResolveResult(
        cycles_completed=cycles,
        xp_gained={action.skill_id: xp_delta} if xp_delta else {},
        items_consumed=dict(consumed),
        items_gained=dict(gained),
        overflowed_items=dict(overflowed),
        level_ups={skill: tuple(values) for skill, values in level_ups.items()},
        stop_reason=stop_reason,
        state=new_state,
        active=new_active,
        elapsed_ms=resolved_ms,
    )


class UniformResolver:
    """The shipped uniform cycle algorithm behind the resolver protocol."""

    def resolve(
        self,
        state: CharacterState,
        action: Action,
        ctx: ResolveContext,
        budget_ms: int,
        rng: RandomSource,
    ) -> ResolveResult:
        """Consume whole cycles without spending the partial remainder."""
        return _resolve_uniform(state, action, ctx, budget_ms, rng)


ACTION_RESOLVERS: Mapping[str, ActionResolver] = MappingProxyType(
    {"uniform": UniformResolver()}
)


def resolve(
    state: CharacterState,
    active: ActiveAction,
    content: ContentIndex,
    now: datetime,
    rng: RandomSource,
    *,
    resolvers: Mapping[str, ActionResolver] = ACTION_RESOLVERS,
) -> tuple[CharacterState, ActiveAction | None, ResolveResult]:
    """Clip elapsed time, dispatch by content resolver, and apply shared stops."""
    action = content.action(active.action_id)
    requirement_lost = any(
        code != ErrorCode.MISSING_INPUTS
        for code in unmet_requirements(action, state, content)
    )
    if now < active.last_resolved_at:
        reason = StopReason.REQUIREMENT_LOST if requirement_lost else None
        next_active = None if requirement_lost else active
        return (
            state,
            next_active,
            ResolveResult(
                0,
                {},
                {},
                {},
                {},
                {},
                reason,
                state=state,
                active=next_active,
                details={"level_ups": {}, "stop_reason": reason},
            ),
        )
    caps = resolve_caps(state, content)
    cap_ms = int(caps.offline_hours * 3_600_000)
    elapsed_ms = _milliseconds(now - active.last_resolved_at)
    ctx = ResolveContext(content, active, caps, modifier_groups(state, content))
    if action.resolver is None:
        raise ValueError(f"action {action.id!r} has no resolver")
    result = resolvers[action.resolver].resolve(
        state, action, ctx, min(elapsed_ms, cap_ms), rng
    )
    if result.state is None:
        raise ValueError(f"resolver {action.resolver!r} returned no character state")
    new_state = result.state
    reason = result.stop_reason
    if reason is None and result.cycles_completed > 0 and elapsed_ms > cap_ms:
        reason = StopReason.OFFLINE_CAP
    if requirement_lost:
        reason = StopReason.REQUIREMENT_LOST
    result = replace(
        result,
        stop_reason=reason,
        active=None if reason else result.active,
        details={
            **result.details,
            "level_ups": {
                skill: list(levels) for skill, levels in result.level_ups.items()
            },
            "stop_reason": reason,
        },
    )
    return new_state, result.active, result
