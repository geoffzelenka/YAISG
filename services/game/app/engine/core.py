"""Pure lazy-resolution mechanics for timed game actions."""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field, replace
from datetime import datetime, timedelta
from enum import StrEnum
from typing import Protocol

from app.content.loader import ContentIndex
from app.content.schemas import Action, CapType, Drop, Modifier, ModifierType
from app.engine.levels import level_for_xp


@dataclass(frozen=True)
class Caps:
    """Resolved limits which constrain character activity."""

    offline_hours: float
    inventory_slots: int
    market_listings: int
    estate_upgrade_slots: int


@dataclass(frozen=True)
class CharacterState:
    """All character data needed by the pure action engine."""

    skills_xp: Mapping[str, int]
    skill_levels: Mapping[str, int]
    inventory: Mapping[str, int]
    gold: int
    realm_id: str
    installed_upgrades: tuple[str, ...] = ()
    realm_tier: int = 0
    cap_bonuses: Mapping[CapType, float] = field(default_factory=dict)


@dataclass(frozen=True)
class ActiveAction:
    """Timestamps for a character's currently repeating action."""

    action_id: str
    started_at: datetime
    last_resolved_at: datetime


class StopReason(StrEnum):
    """Reasons resolution automatically ends an action."""

    INPUTS_EXHAUSTED = "inputs_exhausted"
    OFFLINE_CAP = "offline_cap"
    INVENTORY_FULL = "inventory_full"


@dataclass(frozen=True)
class ResolveResult:
    """Summary of changes produced by one lazy resolution call."""

    cycles_completed: int
    xp_gained: Mapping[str, int]
    items_consumed: Mapping[str, int]
    items_gained: Mapping[str, int]
    overflowed_items: Mapping[str, int]
    level_ups: Mapping[str, tuple[int, ...]]
    stop_reason: StopReason | None


class ErrorCode(StrEnum):
    """Stable error codes returned by action-start validation."""

    INSUFFICIENT_LEVEL = "INSUFFICIENT_LEVEL"
    WRONG_REALM = "WRONG_REALM"
    MISSING_INPUTS = "MISSING_INPUTS"


@dataclass(frozen=True)
class Ok:
    """Successful result from action-start validation."""


OK = Ok()


class RandomSource(Protocol):
    """Random operations used by drop resolution."""

    def random(self) -> float:
        """Return a value in the half-open interval [0, 1)."""

    def randint(self, a: int, b: int) -> int:
        """Return an integer in the inclusive interval [a, b]."""


@dataclass(frozen=True)
class CycleRewards:
    """Rewards generated by one action cycle."""

    xp: int
    drops: tuple[tuple[str, int], ...]


class CycleRewardStrategy(Protocol):
    """Swappable per-cycle reward behavior, including future combat."""

    def rewards(
        self,
        action: Action,
        state: CharacterState,
        content: ContentIndex,
        rng: RandomSource,
    ) -> CycleRewards:
        """Return rewards for one completed cycle."""


def _realm_tags(state: CharacterState, content: ContentIndex) -> set[str]:
    return set(content.realm(state.realm_id).tags)


def _tags_match(required: Sequence[str], actual: set[str]) -> bool:
    return "*" in required or bool(set(required) & actual)


def _active_modifiers(
    action: Action, state: CharacterState, content: ContentIndex
) -> list[Modifier]:
    realm = content.realm(state.realm_id)
    modifiers = list(realm.modifiers)
    for tier in realm.project.tiers:
        if tier.tier <= state.realm_tier:
            modifiers.extend(tier.modifiers)
    realm_tags = set(realm.tags)
    for upgrade_id in state.installed_upgrades:
        upgrade = content.upgrade(upgrade_id)
        if _tags_match(upgrade.realm_tags, realm_tags):
            modifiers.extend(upgrade.modifiers)
    return [
        modifier
        for modifier in modifiers
        if modifier.skill_id is None or modifier.skill_id == action.skill_id
    ]


def _modifier_total(
    modifier_type: ModifierType,
    action: Action,
    state: CharacterState,
    content: ContentIndex,
) -> float:
    return sum(
        modifier.value
        for modifier in _active_modifiers(action, state, content)
        if modifier.type == modifier_type
    )


def effective_cycle_time(
    action: Action, state: CharacterState, content: ContentIndex
) -> int:
    """Return cycle milliseconds after applying all additive modifiers once."""
    percent = _modifier_total(ModifierType.CYCLE_TIME_PCT, action, state, content)
    return max(1, int(action.cycle_ms * (1 + percent / 100)))


def effective_xp(action: Action, state: CharacterState, content: ContentIndex) -> int:
    """Return XP per cycle after applying all additive modifiers once."""
    percent = _modifier_total(ModifierType.XP_PCT, action, state, content)
    return max(0, int(action.xp * (1 + percent / 100)))


def effective_drops(
    action: Action, state: CharacterState, content: ContentIndex
) -> tuple[Drop, ...]:
    """Return drop entries with additively modified chances."""
    percent = _modifier_total(
        ModifierType.EXTRA_DROP_CHANCE_PCT, action, state, content
    )
    multiplier = 1 + percent / 100
    return tuple(
        drop.model_copy(update={"chance": min(1.0, max(0.0, drop.chance * multiplier))})
        for drop in action.drops
    )


class StandardCycleRewards:
    """Standard skilling XP and random drop-table rewards."""

    def rewards(
        self,
        action: Action,
        state: CharacterState,
        content: ContentIndex,
        rng: RandomSource,
    ) -> CycleRewards:
        """Roll each drop independently and return this cycle's rewards."""
        return self.rewards_from_values(
            effective_xp(action, state, content),
            effective_drops(action, state, content),
            rng,
        )

    def rewards_from_values(
        self, xp: int, drops: Sequence[Drop], rng: RandomSource
    ) -> CycleRewards:
        """Roll rewards from effective values cached for a resolution segment."""
        rolled_drops = tuple(
            (drop.item_id, rng.randint(*drop.qty))
            for drop in drops
            if rng.random() < drop.chance
        )
        return CycleRewards(xp, rolled_drops)


STANDARD_REWARDS = StandardCycleRewards()


def resolve_caps(state: CharacterState, content: ContentIndex) -> Caps:
    """Resolve base caps plus active realm-tier, upgrade, and state bonuses."""
    bonuses: defaultdict[CapType, float] = defaultdict(float, state.cap_bonuses)
    realm = content.realm(state.realm_id)
    for tier in realm.project.tiers:
        if tier.tier <= state.realm_tier:
            for bonus in tier.cap_bonuses:
                bonuses[bonus.cap] += bonus.value
    realm_tags = set(realm.tags)
    for upgrade_id in state.installed_upgrades:
        upgrade = content.upgrade(upgrade_id)
        if _tags_match(upgrade.realm_tags, realm_tags):
            for bonus in upgrade.cap_bonuses:
                bonuses[bonus.cap] += bonus.value
    base = content.caps
    return Caps(
        offline_hours=base.offline_hours + bonuses[CapType.OFFLINE_HOURS],
        inventory_slots=int(base.inventory_slots + bonuses[CapType.INVENTORY_SLOTS]),
        market_listings=int(base.market_listings + bonuses[CapType.MARKET_LISTINGS]),
        estate_upgrade_slots=int(
            base.estate_upgrade_slots + bonuses[CapType.ESTATE_UPGRADE_SLOTS]
        ),
    )


def can_start(
    action_id: str, state: CharacterState, content: ContentIndex
) -> Ok | ErrorCode:
    """Validate level, realm availability, and one cycle of inputs."""
    action = content.action(action_id)
    if state.skill_levels.get(action.skill_id, 1) < action.level_required:
        return ErrorCode.INSUFFICIENT_LEVEL
    if not _tags_match(action.realm_tags, _realm_tags(state, content)):
        return ErrorCode.WRONG_REALM
    if any(
        state.inventory.get(entry.item_id, 0) < entry.qty for entry in action.inputs
    ):
        return ErrorCode.MISSING_INPUTS
    return OK


def _milliseconds(delta: timedelta) -> int:
    return delta.days * 86_400_000 + delta.seconds * 1_000 + delta.microseconds // 1_000


def resolve(
    state: CharacterState,
    active: ActiveAction,
    content: ContentIndex,
    now: datetime,
    rng: RandomSource,
    *,
    reward_strategy: CycleRewardStrategy = STANDARD_REWARDS,
) -> tuple[CharacterState, ActiveAction | None, ResolveResult]:
    """Resolve every eligible full cycle, preserving any partial remainder."""
    if now < active.last_resolved_at:
        # A server clock can move backwards slightly during correction. Treat
        # that interval as no elapsed time rather than failing a routine read.
        return state, active, ResolveResult(0, {}, {}, {}, {}, {}, None)
    action = content.action(active.action_id)
    caps = resolve_caps(state, content)
    cap_ms = int(caps.offline_hours * 3_600_000)
    elapsed_ms = _milliseconds(now - active.last_resolved_at)
    available_ms = min(elapsed_ms, cap_ms)
    inventory = {item_id: qty for item_id, qty in state.inventory.items() if qty > 0}
    xp = dict(state.skills_xp)
    levels = dict(state.skill_levels)
    consumed: defaultdict[str, int] = defaultdict(int)
    gained: defaultdict[str, int] = defaultdict(int)
    overflowed: defaultdict[str, int] = defaultdict(int)
    level_ups: defaultdict[str, list[int]] = defaultdict(list)
    resolved_ms = 0
    cycles = 0
    stop_reason: StopReason | None = None
    effective_level: int | None = None
    cycle_ms = 0
    standard_xp = 0
    standard_drops: tuple[Drop, ...] = ()

    while True:
        current_state = replace(
            state, skills_xp=xp, skill_levels=levels, inventory=inventory
        )
        current_level = levels.get(action.skill_id, 1)
        if current_level != effective_level:
            cycle_ms = effective_cycle_time(action, current_state, content)
            if reward_strategy is STANDARD_REWARDS:
                standard_xp = effective_xp(action, current_state, content)
                standard_drops = effective_drops(action, current_state, content)
            effective_level = current_level
        if resolved_ms + cycle_ms > available_ms:
            break
        if any(inventory.get(entry.item_id, 0) < entry.qty for entry in action.inputs):
            stop_reason = StopReason.INPUTS_EXHAUSTED
            break

        for entry in action.inputs:
            inventory[entry.item_id] -= entry.qty
            consumed[entry.item_id] += entry.qty
            if inventory[entry.item_id] == 0:
                del inventory[entry.item_id]

        if reward_strategy is STANDARD_REWARDS:
            rewards = STANDARD_REWARDS.rewards_from_values(
                standard_xp, standard_drops, rng
            )
        else:
            rewards = reward_strategy.rewards(action, current_state, content, rng)
        skill_xp = xp.get(action.skill_id, 0) + rewards.xp
        previous_level = levels.get(action.skill_id, 1)
        next_level = level_for_xp(skill_xp, content.xp_curve.levels)
        xp[action.skill_id] = skill_xp
        levels[action.skill_id] = next_level
        if next_level > previous_level:
            level_ups[action.skill_id].extend(range(previous_level + 1, next_level + 1))

        cycle_overflow = False
        for item_id, quantity in rewards.drops:
            current_quantity = inventory.get(item_id, 0)
            has_slot = item_id in inventory or len(inventory) < caps.inventory_slots
            available_stack = max(
                0, content.item(item_id).stack_limit - current_quantity
            )
            granted = min(quantity, available_stack) if has_slot else 0
            discarded = quantity - granted
            if granted:
                inventory[item_id] = current_quantity + granted
                gained[item_id] += granted
            if discarded:
                overflowed[item_id] += discarded
                cycle_overflow = True
        cycles += 1
        resolved_ms += cycle_ms
        # Capacity loss takes precedence when the same cycle also exhausts inputs:
        # it is the first irreversible constraint encountered while granting rewards.
        if cycle_overflow:
            stop_reason = StopReason.INVENTORY_FULL
            break
        if action.inputs and any(
            inventory.get(entry.item_id, 0) < entry.qty for entry in action.inputs
        ):
            stop_reason = StopReason.INPUTS_EXHAUSTED
            break

    if stop_reason is None and cycles > 0 and elapsed_ms > cap_ms:
        stop_reason = StopReason.OFFLINE_CAP
    new_state = replace(state, skills_xp=xp, skill_levels=levels, inventory=inventory)
    xp_delta = xp.get(action.skill_id, 0) - state.skills_xp.get(action.skill_id, 0)
    result = ResolveResult(
        cycles_completed=cycles,
        xp_gained={action.skill_id: xp_delta} if xp_delta else {},
        items_consumed=dict(consumed),
        items_gained=dict(gained),
        overflowed_items=dict(overflowed),
        level_ups={skill: tuple(values) for skill, values in level_ups.items()},
        stop_reason=stop_reason,
    )
    if stop_reason is not None:
        return new_state, None, result
    new_active = replace(
        active,
        last_resolved_at=active.last_resolved_at + timedelta(milliseconds=resolved_ms),
    )
    return new_state, new_active, result
